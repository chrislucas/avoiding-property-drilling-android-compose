// O daemon do Gradle roda sob Java 25, cujo bytecode (major 69) o ASM do
// Robolectric 4.13 nao consegue reinstrumentar. Forcamos as tarefas de teste
// unitario a rodarem sob uma JVM Java 21 (suportada pelo Robolectric).
tasks.withType<Test>().configureEach {
    javaLauncher.set(
        javaToolchains.launcherFor {
            languageVersion.set(JavaLanguageVersion.of(21))
        }
    )
}

